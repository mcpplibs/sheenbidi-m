#!/usr/bin/env python3
"""Write the module sources and the generated macro test from the SheenBidi headers.

- src/sheenbidi.cppm exports every type, struct tag and SB_PUBLIC function of
  the installed headers by `export using` (the upstream globals, unchanged),
  and re-exports the macros module.
- src/macros.cppm holds, in mcpplibs::mwrap::sheenbidi::macros under their
  own names:
    * the object-like macros (SBLevelInvalid, SBLevelMax, SBLevelDefaultLTR,
      SBCodepointInvalid, SHEENBIDI_VERSION_* …) as `inline constexpr` of the
      type of the macro's own expansion (the version string as a reference to
      a constexpr char array);
    * the function-like macros (SBBidiTypeIsStrong, SBCodepointIsValid,
      SBGeneralCategoryIsLetter, SBUInt8InRange …) as constexpr function
      templates whose body *is* the macro, expanded on the parameters;
    * the enumerators of the headers' unnamed enums (SBBidiType*,
      SBGeneralCategory*, SBScript*, SBStringEncoding*, SBTrue / SBFalse):
      an unnamed enumeration is TU-local, so its enumerators cannot be
      exported as they are. Each is a constant of the typedef the header
      gives its values (`typedef SBUInt8 SBBidiType;` follows the enum).
- tests/macros_mix_test.cpp checks each mapping against the raw header in a
  translation unit that includes it beside the import.

With --check, nothing is written and a difference fails.
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import fetch, surface  # noqa: E402

# Macros that stay macros, in <mwrap/sheenbidi/macros.hpp> (which is <SheenBidi/SheenBidi.h>).
SIDE_HEADER = {
    'SB_PUBLIC': 'an attribute of declarations (dllimport/dllexport under SB_CONFIG_DLL_*)',
    'SB_DEPRECATED': 'an attribute of declarations',
    'SB_EXTERN_C_BEGIN': 'opens an extern "C" block',
    'SB_EXTERN_C_END': 'closes an extern "C" block',
}


def excluded(name: str) -> str | None:
    if re.fullmatch(r'_SB_PUBLIC_\w+_H|_SHEENBIDI_H', name):
        return 'include guard'
    return None


def classify(sf):
    strings, constants, functions = [], [], []
    for macro in sf.macros.values():
        if macro.name in SIDE_HEADER or excluded(macro.name):
            continue
        if macro.params is not None:
            functions.append(macro)
        elif macro.body.startswith('"'):
            strings.append(macro.name)
        else:
            constants.append(macro.name)
    return strings, constants, functions


GUARD = '#include <SheenBidi/SheenBidi.h>'

ROOT_HEADER = '''// Generated by tools/gen_exports.py from the SheenBidi 3.0.0 headers — do not
// edit by hand.
//
// mcpplibs.mwrap.sheenbidi — SheenBidi, the Unicode Bidirectional Algorithm
// (UAX #9, Unicode 17.0.0), as a C++ module. Every exported name is the
// upstream global of <SheenBidi/SheenBidi.h>, unchanged: the types and struct
// tags, and every SB_PUBLIC function (SBAlgorithm, SBParagraph, SBLine,
// SBMirrorLocator, SBScriptLocator, SBCodepoint, SBAllocator, SBVersion). The
// root also re-exports the macro and enumerator mappings. The library is
// compat.sheenbidi, built from the same release.
module;
''' + GUARD + '''

export module mcpplibs.mwrap.sheenbidi;

export import mcpplibs.mwrap.sheenbidi.macros;
'''

MACROS_HEADER = '''// Generated by tools/gen_exports.py from the SheenBidi 3.0.0 headers — do not
// edit by hand.
//
// mcpplibs.mwrap.sheenbidi.macros — what <SheenBidi/SheenBidi.h> declares that
// a named module cannot export as it is, under the original names in
// mcpplibs::mwrap::sheenbidi::macros:
//
//   - object-like macros (SBLevelInvalid, SBLevelMax, SBLevelDefaultLTR,
//     SBLevelDefaultRTL, SBCodepointInvalid, SBCodepointFaulty,
//     SBCodepointMax, SB_TEXT_API_SUPPORTED, SHEENBIDI_VERSION_*) as `inline
//     constexpr`, each of the type its macro expands to (SBLevelMax is an
//     `int`, as 125 is; SBCodepointInvalid a `uint32_t`, as UINT32_MAX is), the
//     version string as a reference to a constexpr char array;
//   - function-like macros (SBUInt8InRange, SBBidiTypeIsStrong,
//     SBCodepointIsValid, SBGeneralCategoryIsLetter …) as constexpr function
//     templates. Each body is the macro itself, expanded on the parameters
//     while the header's macros are defined (the declarator is parenthesised
//     so the name is not expanded): the result has the macro's value and
//     type for every argument type. Each argument is evaluated once, before
//     the call;
//   - the enumerators of the headers' unnamed enums (SBBidiType*,
//     SBGeneralCategory*, SBScript*, SBStringEncoding*, SBTrue, SBFalse). An
//     unnamed enumeration is TU-local, so they cannot be exported as they are:
//     each is a constant of the typedef the header gives its values (the enum
//     of SBBidiTypeL is followed by `typedef SBUInt8 SBBidiType;`).
//
// Attributes and the extern "C" brackets stay macros, in
// <mwrap/sheenbidi/macros.hpp>, included before the import.
// tools/check_exports.py accounts for every macro.
module;
''' + GUARD + '''
'''


def render_root(sf) -> str:
    out = [ROOT_HEADER]
    out.append(f'// types ({len(sf.types)})')
    out += [f'export using ::{n};' for n in sf.types]
    out.append(f'\n// struct tags ({len(sf.tags)}; the opaque ones are declared, not defined)')
    out += [f'export using ::{n};' for n in sf.tags]
    out.append(f'\n// functions ({len(sf.functions)}; {", ".join(sf.deprecated)} is SB_DEPRECATED upstream)')
    out += [f'export using ::{n};' for n in sf.functions]
    return '\n'.join(out) + '\n'


def function(macro) -> list[str]:
    tparams = ', '.join(f'class T{i}' for i in range(len(macro.params)))
    params = ', '.join(f'T{i} {p}' for i, p in enumerate(macro.params))
    call = f'{macro.name}({", ".join(macro.params)})'
    return [f'template <{tparams}>', f'constexpr auto ({macro.name})({params}) noexcept {{ return {call}; }}']


def render_macros(sf) -> str:
    strings, constants, functions = classify(sf)
    out = [MACROS_HEADER]
    out.append('export module mcpplibs.mwrap.sheenbidi.macros;\n')
    out.append('// The header\'s values, taken while its macros are defined (module linkage).')
    out.append('namespace mwrap_sheenbidi_capture {')
    out += [f'inline constexpr auto value_{n} = {n};' for n in constants]
    out += [f'inline constexpr char value_{n}[] = {n};' for n in strings]
    out.append('}  // namespace mwrap_sheenbidi_capture\n')
    out.append('// ── computation macros, defined while the header\'s macros are ──────────────')
    out.append('export namespace mcpplibs::mwrap::sheenbidi::macros {\n')
    for macro in functions:
        out.append(f'// #define {macro.name}({", ".join(macro.params)}) {macro.body}')
        out += function(macro)
    out.append('\n}  // namespace mcpplibs::mwrap::sheenbidi::macros\n')
    out.append('// Every mapped object-like name, so the definitions below are not rewritten.')
    out += [f'#undef {n}' for n in constants + strings]
    out.append('\nnamespace c = mwrap_sheenbidi_capture;\n')
    out.append('export namespace mcpplibs::mwrap::sheenbidi::macros {\n')
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    out += [f'inline constexpr auto {n} = c::value_{n};' for n in constants]
    out.append('\n// ── strings ─────────────────────────────────────────────────────────────────')
    out += [f'inline constexpr auto& {n} = c::value_{n};' for n in strings]
    by_type: dict[str, list[str]] = {}
    for e, t in sf.enumerators.items():
        by_type.setdefault(t, []).append(e)
    for t, names in by_type.items():
        out.append(f'\n// ── enumerators of the unnamed enum whose values are {t} ({len(names)}) ' + '─' * max(0, 20 - len(t)))
        out += [f'inline constexpr ::{t} {n} = ::{n};' for n in names]
    out.append('\n}  // namespace mcpplibs::mwrap::sheenbidi::macros')
    return '\n'.join(out) + '\n'


TEST_HEADER = '''// Generated by tools/gen_exports.py from the SheenBidi 3.0.0 headers — do not
// edit by hand.
//
// Every mapping against the raw header, in one translation unit that includes
// <mwrap/sheenbidi/macros.hpp> (that is, <SheenBidi/SheenBidi.h>) beside the
// import:
//
//   - each constant has its macro's type and value (the macro is set aside
//     with push_macro around the comparison: while it is defined it expands
//     even inside `m::NAME`);
//   - each enumerator constant has the value of the header's enumerator and
//     the typedef the header gives it;
//   - each function gives the macro's value and type for every argument of
//     the sample sets (every 8-bit value, 16- and 32-bit boundaries, code
//     points around the surrogates and the end of Unicode, ints); a
//     function-like macro is not expanded when its name is followed by `)`,
//     so `(m::NAME)(args)` calls the function beside the macro `NAME(args)`.
#include <mwrap/sheenbidi/macros.hpp>
#include <gtest/gtest.h>

import std;
import mcpplibs.mwrap.sheenbidi;

namespace m = mcpplibs::mwrap::sheenbidi::macros;
'''

TEST_SAMPLES = '''
namespace {

std::vector<SBUInt8> u8s() {  // every 8-bit value: every bidi type, category, script
    std::vector<SBUInt8> out;
    for (int i = 0; i < 256; ++i) out.push_back(static_cast<SBUInt8>(i));
    return out;
}
std::vector<SBUInt16> u16s() { return {0, 1, 0x7f, 0xff, 0x100, 0xd7ff, 0xd800, 0xdbff, 0xdc00, 0xdfff, 0xe000, 0xfffd, 0xffff}; }
std::vector<SBUInt32> u32s() {
    return {0u, 0x41u, 0x5d0u, 0xd7ffu, 0xd800u, 0xdbffu, 0xdc00u, 0xdfffu, 0xe000u, 0xfffdu, 0xffffu,
            0x10000u, 0x10940u, 0x10ffffu, 0x110000u, 0x7fffffffu, 0x80000000u, 0xffffffffu};
}
std::vector<int> ints() { return {0, 1, 2, 3, 4, 10, 14, 15, 23, 24, 125, 253, 254, 255, 256, -1, -2, 0xd800, 0x10ffff, 0x110000}; }

// Calls `check` with every sample of every argument type.
template <class F>
void unary(F check) {
    for (auto v : u8s()) check(v);
    for (auto v : u16s()) check(v);
    for (auto v : u32s()) check(v);
    for (auto v : ints()) check(v);
}
template <class F>
void ternary(F check) {
    auto over = [&](const auto& values) {
        for (auto v : values)
            for (auto s : values)
                for (auto e : values) check(v, s, e);
    };
    over(u16s());
    over(u32s());
    over(ints());
    over(std::vector<SBUInt8>{0, 1, 3, 4, 10, 11, 14, 15, 23, 24, 127, 128, 254, 255});
}

}  // namespace
'''


def render_test(sf) -> str:
    strings, constants, functions = classify(sf)
    out = [TEST_HEADER]
    out.append('// ── constants ───────────────────────────────────────────────────────────────')
    for n in constants:
        out.append(f'constexpr auto raw_{n} = {n};')
    for n in strings:
        out.append(f'using raw_type_{n} = decltype({n});')
        out.append(f'constexpr std::string_view raw_{n} = {n};')
    for n in constants:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<decltype(m::{n}), decltype(raw_{n})> && m::{n} == raw_{n});',
                f'#pragma pop_macro("{n}")']
    for n in strings:
        out += [f'#pragma push_macro("{n}")', f'#undef {n}',
                f'static_assert(std::is_same_v<std::remove_cvref_t<decltype(m::{n})>, std::remove_cvref_t<raw_type_{n}>>);',
                f'static_assert(std::string_view(m::{n}) == raw_{n});',
                f'#pragma pop_macro("{n}")']
    out.append('\n// ── enumerators ─────────────────────────────────────────────────────────────')
    for n, t in sf.enumerators.items():
        out.append(f'static_assert(std::is_same_v<decltype(m::{n}), const ::{t}> && m::{n} == ::{n});')
    out.append(TEST_SAMPLES)
    out.append('// ── computation macros ──────────────────────────────────────────────────────')
    for macro in functions:
        params = ', '.join(f'auto {p}' for p in macro.params)
        args = ', '.join(macro.params)
        arity = {1: 'unary', 3: 'ternary'}[len(macro.params)]
        out.append(f'TEST(MacroFunctions, {macro.name}) {{')
        out.append(f'    {arity}([]({params}) {{')
        out += [f'        static_assert(std::is_same_v<decltype({macro.name}({args})), decltype((m::{macro.name})({args}))>);',
                f'        EXPECT_EQ({macro.name}({args}), (m::{macro.name})({args}));']
        out.append('    });')
        out.append('}')
    return '\n'.join(out) + '\n'


def outputs(root: Path) -> dict[Path, str]:
    sf = surface(fetch(root))
    return {
        root / 'src/sheenbidi.cppm': render_root(sf),
        root / 'src/macros.cppm': render_macros(sf),
        root / 'tests/macros_mix_test.cpp': render_test(sf),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for path, text in outputs(root).items():
        # Text mode: a checkout with CRLF line ends (Windows) reads the same.
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue  # unchanged: the timestamp is kept, nothing rebuilds
        if args.check:
            stale.append(path.relative_to(root).as_posix())
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
            print('wrote', path.relative_to(root).as_posix())
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
